"""Where townsfolk stand and sleep in each building, written for NPC.gd (scripts/npc/HouseLayouts.gd).

A spec gives these in the building's own local units; NPC.gd wants them relative to the building's door
marker in Cidade.tscn, in town units. The marker sits at the middle of the door, MARKER_Z inside the wall."""
from .core import TOWN_SCALE

MARKER_Z = -0.5


def npc_layout(h):
    """{"slots": [...], "bed": (pos, angle) or None, "approach": pos or None}, positions relative to the door marker"""
    npc = h.spec.get("npc")
    if not npc:
        return None
    mx, mz = h.door_x, MARKER_Z
    def rel(p):
        x, y, z = (p[0], 0.0, p[1]) if len(p) == 2 else p
        return (round((x - mx) * TOWN_SCALE, 3), round(y * TOWN_SCALE, 3), round((z - mz) * TOWN_SCALE, 3))
    out = {"slots": [rel(p) for p in npc["slots"]], "bed": None, "approach": None}
    if npc.get("bed"):
        *pos, angle = npc["bed"]
        out["bed"] = (rel(pos), angle)
    if npc.get("bed_approach"):
        out["approach"] = rel(npc["bed_approach"])
    return out


def _v(p):
    return "Vector3(%s, %s, %s)" % tuple(repr(float(c)) for c in p)


def write_gd(layouts, path):
    """layouts: {location name: npc_layout(...)}"""
    L = ["# Generated by art_source/tools/gen_buildings.py from art_source/tools/specs/ - do not edit by hand.",
         "# Where townsfolk stand and sleep in the 2D buildings, relative to each building's door marker (see NPC.gd).",
         "extends RefCounted", "",
         "# Indoor spots: the first is the owner's own (or the worker's post)",
         "const INTERIOR_SLOTS := {"]
    for name, lay in layouts.items():
        L.append('\t"%s": [%s],' % (name, ", ".join(_v(p) for p in lay["slots"])))
    L += ["}", "", "# The foot of the bed and which way the head points (degrees around Y)", "const BED_SPOTS := {"]
    for name, lay in layouts.items():
        if lay["bed"]:
            L.append('\t"%s": [%s, %s],' % (name, _v(lay["bed"][0]), repr(float(lay["bed"][1]))))
    L += ["}", "", "# Upstairs beds: where to walk to first, beside the bed on the upper floor", "const BED_APPROACH := {"]
    for name, lay in layouts.items():
        if lay["approach"]:
            L.append('\t"%s": %s,' % (name, _v(lay["approach"])))
    L += ["}", ""]
    open(path, "w").write("\n".join(L))
